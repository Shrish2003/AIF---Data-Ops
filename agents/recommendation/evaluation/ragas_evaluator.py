import os
import logging
import asyncio

logger = logging.getLogger(__name__)

# Try importing RAGAS modules dynamically to ensure missing installation is handled gracefully.
try:
    import ragas
    from ragas.dataset_schema import SingleTurnSample
    from ragas.metrics import FactualCorrectness
    RAGAS_AVAILABLE = True
except ImportError:
    RAGAS_AVAILABLE = False
    SingleTurnSample = None
    FactualCorrectness = None

class EvaluationBackendUnavailableError(Exception):
    """Raised when RAGAS or the configured evaluation LLM backend is not available."""
    pass

def get_evaluation_llm():
    """
    Instantiate the Configured local Ollama Evaluation Backend.
    """
    base_url = os.getenv("OLLAMA_BASE_URL", "http://localhost:11434")
    model_name = os.getenv("OLLAMA_MODEL", "llama3.2:3b")

    try:
        from langchain_community.chat_models import ChatOllama
        logger.info(f"Initializing ChatOllama for RAGAS evaluation with model: {model_name}, host: {base_url}")
        return ChatOllama(model=model_name, base_url=base_url)
    except ImportError as e:
        logger.error(f"Failed to import ChatOllama: {e}")
        raise EvaluationBackendUnavailableError(
            "Missing required libraries for Ollama. Ensure langchain-community is installed."
        )

class RagasEvaluator:
    """
    ==========================================================
    RAGAS Evaluator
    
    Responsibility:
        Calculate objective metrics (specifically Factual Correctness)
        using Ragas and the Configured Evaluation Backend.
        
    Design:
        - Decoupled from specific LLM providers.
        - Provider-agnostic backend resolver.
        - Graceful error handling for missing dependencies.
    ==========================================================
    """

    def __init__(self):
        logger.info(f"Ragas Evaluator initialized. RAGAS library available: {RAGAS_AVAILABLE}")

    def evaluate_correctness(self, generated_recommendation, expected_recommendation):
        """
        Evaluate factual correctness of generated recommendation against expected recommendation.
        
        Args:
            generated_recommendation (str): The recommendation generated by the pipeline.
            expected_recommendation (str): The expected recommendation from Golden Truth.
            
        Returns:
            float: Factual correctness score between 0.0 and 1.0.
            
        Raises:
            EvaluationBackendUnavailableError: If evaluation cannot run.
        """
        if not RAGAS_AVAILABLE:
            raise EvaluationBackendUnavailableError("Ragas package is not installed or import failed.")

        try:
            logger.info("Initializing LLM backend...")
            llm = get_evaluation_llm()
            logger.info(f"LLM backend initialized: {llm}")
            
            logger.info("Initializing FactualCorrectness metric...")
            scorer = FactualCorrectness(llm=llm)
            logger.info("FactualCorrectness metric initialized successfully.")
            
            sample = SingleTurnSample(
                response=generated_recommendation,
                reference=expected_recommendation
            )
            
            # Setup an event loop to run the scoring task
            try:
                loop = asyncio.get_event_loop()
            except RuntimeError:
                loop = asyncio.new_event_loop()
                asyncio.set_event_loop(loop)
                
            logger.info(f"Sending evaluation request for response: {generated_recommendation[:60]}... against reference: {expected_recommendation[:60]}...")
            
            if loop.is_running():
                # If loop is already running (e.g. under FastAPI), execute thread-safely
                import nest_asyncio
                nest_asyncio.apply()
                
                # Check if sync scoring is supported
                try:
                    result = scorer.single_turn_score(sample)
                except (AttributeError, TypeError):
                    coro = scorer.single_turn_ascore(sample)
                    result = asyncio.run_coroutine_threadsafe(coro, loop).result()
            else:
                try:
                    result = scorer.single_turn_score(sample)
                except (AttributeError, TypeError):
                    coro = scorer.single_turn_ascore(sample)
                    result = loop.run_until_complete(coro)
            
            logger.info(f"Evaluation response received: {result}")
            
            if hasattr(result, "value"):
                score = float(result.value)
            else:
                # Fallback in case format is simple dict or float
                score = float(result)
                
            logger.info(f"RAGAS evaluation succeeded. Score: {score}")
            return score

        except EvaluationBackendUnavailableError:
            import traceback
            traceback.print_exc()
            raise
        except Exception as e:
            logger.error(f"Unexpected error during RAGAS evaluation execution: {e}")
            import traceback
            traceback.print_exc()
            raise EvaluationBackendUnavailableError(f"RAGAS execution failed: {e}")
